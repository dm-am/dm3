// C# as tokens without comments, by a lexer that refuses any character it has
// no rule for rather than guess: a string it misread would otherwise turn the
// code after it into a "comment" and hide a change there.
//
// Preprocessor directives are tokens, #pragma among them. #region and
// #endregion are the exception: they mean nothing to the compiler and are
// dropped like comments. Of the comments, the generated-code marker and IDE
// suppressions stay, since tools read them.
//
// XML doc comments (///) are comments here, though one project publishes
// them: the build of src/DM.Web.API writes them into DM.Web.API.xml, which
// Swagger loads into the API document. For that project "same code" says
// nothing about the document; compare-code.mjs names such files so that the
// XML of the two builds gets diffed.

import { LexError, Tokens } from "./lexing.mjs";

const DIRECTIVES = [
  /^\/\/\s*<auto-generated/,
  /^\/[/*]\s*ReSharper\s+(?:disable|restore)\b/,
  /^\/\/\s*@formatter:/,
];

// `>` is never joined with a following `>`: in `List<List<int>>` the two are
// separate tokens, and C# itself only joins them in the parser.
const OPERATORS = [
  "??=",
  "<<=",
  "=>",
  "==",
  "!=",
  "<=",
  ">=",
  "&&",
  "||",
  "++",
  "--",
  "+=",
  "-=",
  "*=",
  "/=",
  "%=",
  "&=",
  "|=",
  "^=",
  "<<",
  "->",
  "::",
  "??",
  "?.",
  "..",
];
const SINGLE = "{}()[];,.:?+-*/%&|^!~=<>";
const IDENTIFIER =
  /@?[\p{L}\p{Nl}_][\p{L}\p{Nl}\p{Nd}\p{Mn}\p{Mc}\p{Pc}\p{Cf}]*/uy;
const NUMBER =
  /(?:0[xX][0-9a-fA-F_]+|0[bB][01_]+|(?:[0-9][0-9_]*)?(?:\.[0-9][0-9_]*)?(?:[eE][+-]?[0-9][0-9_]*)?)(?:[uU][lL]?|[lL][uU]?|[fFdDmM])?/y;

/** The end of a char literal that opens at `i`. */
function charEnd(text, i) {
  let j = text[i + 1] === "\\" ? i + 3 : i + 2;
  while (j < text.length && text[j] !== "'" && text[j] !== "\n") j++;
  if (text[j] !== "'") throw new LexError(i, "unterminated character literal");
  return j + 1;
}

/**
 * The end of an interpolation hole that starts at `i` (just past its opening
 * braces) and closes with `braces` closing braces. Strings, characters and
 * brackets inside it are skipped whole, so a brace in them does not count.
 */
function holeEnd(text, i, braces) {
  let depth = 0;
  let j = i;
  while (j < text.length) {
    const c = text[j];
    if (text.startsWith("//", j)) {
      j = text.indexOf("\n", j);
      if (j === -1) break;
    } else if (text.startsWith("/*", j)) {
      const close = text.indexOf("*/", j + 2);
      if (close === -1) break;
      j = close + 2;
    } else if (c === '"' || c === "@" || c === "$") {
      const end = stringEnd(text, j);
      j = end === -1 ? j + 1 : end;
    } else if (c === "'") {
      j = charEnd(text, j);
    } else if (c === "(" || c === "[" || c === "{") {
      depth++;
      j++;
    } else if (c === ")" || c === "]") {
      depth--;
      j++;
    } else if (c === "}") {
      if (depth === 0) return j + braces;
      depth--;
      j++;
    } else if (c === ":" && depth === 0) {
      if (text[j + 1] === ":") {
        j += 2;
        continue;
      }
      // A format specifier runs to the closing braces and holds no brace.
      const close = text.indexOf("}".repeat(braces), j);
      if (close === -1) break;
      return close + braces;
    } else {
      j++;
    }
  }
  throw new LexError(i, "unterminated interpolation");
}

/**
 * The end of a string literal that opens at `i`, or -1 when none does:
 * regular, verbatim (@), interpolated ($, $@, @$) and raw (three or more
 * quotes, with any number of $ for interpolation).
 */
function stringEnd(text, i) {
  let j = i;
  let dollars = 0;
  let verbatim = false;
  if (text[j] === "@") {
    verbatim = true;
    j++;
    while (text[j] === "$") {
      dollars++;
      j++;
    }
  } else {
    while (text[j] === "$") {
      dollars++;
      j++;
    }
    if (text[j] === "@") {
      verbatim = true;
      j++;
    }
  }
  if (text[j] !== '"') return -1;
  let quotes = 0;
  while (text[j + quotes] === '"') quotes++;

  if (!verbatim && quotes >= 3) {
    let k = j + quotes;
    while (k < text.length) {
      if (text[k] === '"') {
        let run = 0;
        while (text[k + run] === '"') run++;
        if (run >= quotes) return k + run;
        k += run;
      } else if (dollars > 0 && text[k] === "{") {
        // Fewer braces than dollars are content; as many open a hole.
        let run = 0;
        while (text[k + run] === "{") run++;
        k += run;
        if (run >= dollars) k = holeEnd(text, k, dollars);
      } else {
        k++;
      }
    }
    throw new LexError(i, "unterminated raw string");
  }

  let k = j + 1;
  while (k < text.length) {
    const c = text[k];
    if (verbatim && c === '"') {
      if (text[k + 1] === '"') k += 2;
      else return k + 1;
    } else if (!verbatim && c === "\\") {
      k += 2;
    } else if (c === '"') {
      return k + 1;
    } else if (!verbatim && c === "\n") {
      break;
    } else if (dollars > 0 && c === "{") {
      if (text[k + 1] === "{") k += 2;
      else k = holeEnd(text, k + 1, 1);
    } else if (dollars > 0 && c === "}") {
      k += text[k + 1] === "}" ? 2 : 1;
    } else {
      k++;
    }
  }
  throw new LexError(i, "unterminated string");
}

/** A preprocessor line: a token, except a region marker, which is nothing. */
function directive(tokens, line, at) {
  const name = /^#\s*([a-z]+)/.exec(line)?.[1];
  if (name === "region" || name === "endregion") return;
  let body = line;
  // #error and #warning carry free text, in which // is not a comment.
  const slashes =
    name === "error" || name === "warning" ? -1 : line.indexOf("//");
  if (slashes >= 0) {
    tokens.comment(line.slice(slashes), at + slashes, DIRECTIVES);
    body = line.slice(0, slashes);
  }
  tokens.push(body.trim().replace(/\s+/g, " "), at);
}

export function csharpTokens(text) {
  const tokens = new Tokens(text);
  let i = 0;
  let lineStart = true;
  while (i < text.length) {
    const c = text[i];
    if (c === "\n") {
      lineStart = true;
      i++;
      continue;
    }
    if (/\s/.test(c)) {
      i++;
      continue;
    }
    if (lineStart && c === "#") {
      let end = text.indexOf("\n", i);
      if (end === -1) end = text.length;
      directive(tokens, text.slice(i, end), i);
      i = end;
      continue;
    }
    lineStart = false;
    if (text.startsWith("//", i)) {
      let end = text.indexOf("\n", i);
      if (end === -1) end = text.length;
      tokens.comment(text.slice(i, end), i, DIRECTIVES);
      i = end;
      continue;
    }
    if (text.startsWith("/*", i)) {
      const close = text.indexOf("*/", i + 2);
      if (close === -1) throw new LexError(i, "unterminated comment");
      tokens.comment(text.slice(i, close + 2), i, DIRECTIVES);
      i = close + 2;
      continue;
    }
    const literalEnd =
      c === '"' || c === "@" || c === "$"
        ? stringEnd(text, i)
        : c === "'"
          ? charEnd(text, i)
          : -1;
    if (literalEnd !== -1) {
      tokens.push(text.slice(i, literalEnd), i);
      i = literalEnd;
      continue;
    }
    IDENTIFIER.lastIndex = i;
    NUMBER.lastIndex = i;
    const word =
      IDENTIFIER.exec(text)?.[0] ??
      (/[0-9]/.test(c) || (c === "." && /[0-9]/.test(text[i + 1]))
        ? NUMBER.exec(text)[0]
        : undefined) ??
      OPERATORS.find((candidate) => text.startsWith(candidate, i)) ??
      (SINGLE.includes(c) ? c : undefined);
    if (word === undefined) {
      throw new LexError(i, `no C# token starts with ${JSON.stringify(c)}`);
    }
    tokens.push(word, i);
    i += word.length;
  }
  return tokens;
}
